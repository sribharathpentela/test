"""Render the PR body -- the closure proof, made readable.

`01-algorithm.md` section 8: render only after the proof, and *emit the proof*
as the provenance table. A reviewer should be able to answer "where did this
value come from?" for every line of the generated file without leaving the PR.

Three things earn their own section because a reviewer has to act on them:

* **values that depart from the module default** -- copying the template is
  deliberate (ADR 0014), but `persistence_rdb_backup_frequency = "12h"` against
  a module default of `null` is a behaviour change and must be visible;
* **values read out of ticket prose into a naming variable** -- grounded, but
  possibly misread (ADR 0016);
* **what a human supplied**, and in which round.
"""

from typing import List, Optional

from ..contracts.models import ModuleContract
from ..resolve.facts import FactsStore
from ..resolve.models import Action, ClosureProof, FactSource
from .hcl_writer import RenderResult, to_hcl

BRANCH_NAMES = {
    1: "ticket / HITL",
    2: "auto-injected",
    3: "template",
    4: "pointer catalogue",
    5: "required",
    6: "module default",
}


def render_pr_body(proof: ClosureProof,
                   contract: ModuleContract,
                   render: RenderResult,
                   facts: Optional[FactsStore] = None,
                   ticket_key: str = "",
                   unit_path: str = "") -> str:
    """Build the markdown body for the pull request."""
    lines: List[str] = []

    title = "Provision `%s`" % contract.module_path
    if ticket_key:
        title += " (%s)" % ticket_key
    lines.append("## %s" % title)
    lines.append("")

    rendered = len(render.rendered)
    omitted = sum(1 for r in proof.resolutions.values()
                  if r.action is Action.OMIT)
    lines.append("Generated by the Deployment Agent from %s."
                 % (ticket_key or "the ticket"))
    lines.append("")
    lines.append("| | |")
    lines.append("|---|---|")
    lines.append("| module | `%s` |" % contract.module_path)
    if unit_path:
        lines.append("| unit | `%s` |" % unit_path)
    lines.append("| variables declared | %d |" % len(contract.variables))
    lines.append("| inputs written | %d |" % rendered)
    lines.append("| left to the module default | %d |" % omitted)
    lines.append("")

    # ---- what needs a decision ------------------------------------------
    divergent = [r for r in _sorted(proof) if r.has_module_default]
    if divergent:
        lines.append("### Values that differ from the module default")
        lines.append("")
        lines.append("Taken from the module's template, which is how the fleet "
                     "stays consistent -- but each one changes behaviour away "
                     "from what the module would do on its own.")
        lines.append("")
        lines.append("| variable | written | module default |")
        lines.append("|---|---|---|")
        for resolution in divergent:
            lines.append("| `%s` | %s | %s |"
                         % (resolution.variable, _cell(resolution.value),
                            _cell(resolution.module_default)))
        lines.append("")

    confirm = [r for r in _sorted(proof)
               if r.disclose and not r.has_module_default
               and r.source in (FactSource.JIRA, FactSource.SUPERVISOR)]
    if confirm:
        lines.append("### Read from the ticket -- please confirm")
        lines.append("")
        lines.append("These decide what the resource is called. The value is "
                     "quoted from the ticket, but the agent cannot tell whether "
                     "the ticket meant it for this field.")
        lines.append("")
        lines.append("| variable | value | quoted from the ticket |")
        lines.append("|---|---|---|")
        for resolution in confirm:
            evidence = (resolution.evidence or "").strip().replace("|", "\\|")
            lines.append("| `%s` | %s | %s |"
                         % (resolution.variable, _cell(resolution.value),
                            ('"%s"' % evidence) if evidence else "--"))
        lines.append("")

    # ---- what a human supplied -------------------------------------------
    if facts is not None:
        human = [r for r in facts.records if r.source is FactSource.HITL]
        if human:
            lines.append("### Supplied by a human")
            lines.append("")
            lines.append("| variable | value | round |")
            lines.append("|---|---|---|")
            for record in sorted(human, key=lambda r: (r.round, r.path)):
                lines.append("| `%s` | %s | %d |"
                             % (record.path, _cell(record.value), record.round))
            lines.append("")

    if render.secrets:
        lines.append("### Secrets")
        lines.append("")
        lines.append("Rendered as `get_env(...)` lookups. No secret value "
                     "passes through the agent: %s."
                     % ", ".join("`%s`" % s for s in render.secrets))
        lines.append("")

    # ---- the closure proof ------------------------------------------------
    lines.append("### Provenance")
    lines.append("")
    lines.append("Every declared variable, and the branch that decided it. "
                 "The agent renders only when this table is complete and "
                 "nothing is left unanswered.")
    lines.append("")
    lines.append("<details><summary>%d variables</summary>"
                 % len(proof.resolutions))
    lines.append("")
    lines.append("| variable | branch | source | value |")
    lines.append("|---|---|---|---|")
    for resolution in _sorted(proof):
        lines.append("| `%s` | %d -- %s | %s | %s |" % (
            resolution.variable,
            int(resolution.branch),
            BRANCH_NAMES.get(int(resolution.branch), ""),
            resolution.source.value if resolution.source else "--",
            _display(resolution),
        ))
    lines.append("")
    lines.append("</details>")
    lines.append("")

    if proof.warnings:
        lines.append("### Warnings")
        lines.append("")
        for warning in proof.warnings:
            lines.append("- %s" % warning)
        lines.append("")

    lines.append("---")
    lines.append("")
    lines.append("*The module reference is not pinned here -- it resolves from "
                 "`common.hcl` (`module_ref`).*")
    return "\n".join(lines) + "\n"


def _sorted(proof: ClosureProof):
    return [proof.resolutions[name] for name in sorted(proof.resolutions)]


def _cell(value) -> str:
    """A value fit for a markdown table cell.

    A rendered HCL block contains newlines, which end the row early and break
    the table for every variable after it.
    """
    rendered = to_hcl(value)
    if "\n" in rendered:
        return "*(block -- see the file)*"
    return "`%s`" % rendered


def _display(resolution) -> str:
    if resolution.action is Action.OMIT:
        return "*omitted*"
    if resolution.action is Action.POINTER:
        return "`include.common.locals.%s`" % resolution.pointer_target
    if resolution.action is Action.SECRET:
        return "`get_env(...)`"
    rendered = to_hcl(resolution.value)
    if "\n" in rendered:
        return "*(block)*"
    return "`%s`" % rendered
